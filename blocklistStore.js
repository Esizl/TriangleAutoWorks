const fs = require('fs')
const path = require('path')
const vm = require('vm')

const BLOCKLIST_PATH = path.join(__dirname, 'public', 'js', 'oilChangeBlocklist.js')

const FILE_HEADER = `/**
 * oilChangeBlocklist.js
 * -----------------------------------------------------------------------
 * Vehicles where the self-service "Oil Change" / "Premium Oil Change"
 * checkboxes should be disabled in Step 3 rather than priced normally.
 *
 * This is NOT about oil type/viscosity — it's about whether the job is
 * something Triangle Auto Works wants to do as a standard mobile/shop
 * line item at all. Reasons so far:
 *
 *   - Skid plate removal required (Range Rover, Land Cruiser) — extra
 *     labor + liability that doesn't fit the flat-rate model.
 *   - Exotic multi-drain-plug dry-sump setups (Lamborghini etc.) — not
 *     something we're doing as a standard service.
 *
 * Matching is by MAKE only, or MAKE + specific MODEL(s) when the issue
 * only affects certain trims of a brand. An entry with models: "all"
 * blocks every model under that make.
 *
 * isOilChangeBlocked() is the single source of truth the configurator
 * calls — never duplicate this check elsewhere.
 *
 * NOTE: This file is regenerated by the admin Site editor
 * (blocklistStore.js). Hand edits to the array will be preserved on
 * load, but formatting/comments inside the array will not.
 * -----------------------------------------------------------------------
 */

`

const FILE_FOOTER = `
/**
 * Returns { blocked: boolean, reason: string|null } for the given
 * make/model. Case-sensitive exact match against VEHICLE_DATA naming —
 * keep make/model spelling here consistent with vehicle-data.js.
 */
function isOilChangeBlocked(make, model) {
    if (!make) return { blocked: false, reason: null };

    const entry = OIL_CHANGE_BLOCKLIST.find(e => e.make === make);
    if (!entry) return { blocked: false, reason: null };

    if (entry.models === "all" || (Array.isArray(entry.models) && entry.models.includes(model))) {
        return { blocked: true, reason: entry.reason };
    }

    return { blocked: false, reason: null };
}

window.OIL_CHANGE_BLOCKLIST = OIL_CHANGE_BLOCKLIST;
window.isOilChangeBlocked = isOilChangeBlocked;
`

// Read oilChangeBlocklist.js off disk and safely extract the array.
// The file assigns to window.*, so the sandbox needs a window stub.
function loadBlocklist() {
    const src = fs.readFileSync(BLOCKLIST_PATH, 'utf8')
    const sandbox = { window: {} }
    vm.createContext(sandbox)
    vm.runInContext(
        src + '\nthis.__BLOCKLIST = OIL_CHANGE_BLOCKLIST;',
        sandbox
    )
    return sandbox.__BLOCKLIST || []
}

// Regenerate the full file from the in-memory array.
function saveBlocklist(entries) {
    const entryText = entries.map(e => {
        const modelsText = e.models === 'all'
            ? '"all"'
            : `[${e.models.map(m => JSON.stringify(m)).join(', ')}]`

        return `    {\n` +
            `        make: ${JSON.stringify(e.make)},\n` +
            `        models: ${modelsText},\n` +
            `        reason: ${JSON.stringify(e.reason)}\n` +
            `    }`
    }).join(',\n')

    const body = entries.length > 0 ? `\n${entryText}\n` : ''
    const fileText = FILE_HEADER +
        `const OIL_CHANGE_BLOCKLIST = [${body}];\n` +
        FILE_FOOTER

    fs.writeFileSync(BLOCKLIST_PATH, fileText, 'utf8')
}

module.exports = { loadBlocklist, saveBlocklist }